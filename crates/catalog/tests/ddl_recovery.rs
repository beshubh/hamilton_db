const DB: &str = "/db/test.db";
const LOG: &str = "/db/test.log";

/// Small, so the workloads start and remove segments.
const SEGMENT: u64 = 32 << 10;

/// `t (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, v INT,
/// pad VARCHAR(200))`.
fn t_schema() -> Schema {
    Schema::new(vec![
        Column::new("id", DataType::BigInt, false),
        Column::new("v", DataType::Int, true),
        Column::new("pad", DataType::Varchar(200), true),
    ])
}

/// `u (id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name
/// VARCHAR(40) UNIQUE, k INT)`.
fn u_schema() -> Schema {
    Schema::new(vec![
        Column::new("id", DataType::Int, false),
        Column::new("name", DataType::Varchar(40), true),
        Column::new("k", DataType::Int, true),
    ])
}

/// A table of many columns, so that its create spills the catalog's
/// `columns` table onto a new page.
fn wide_schema() -> Schema {
    let columns = (0..60).map(|i| Column::new(format!("column_{i:02}"), DataType::Int, i > 0));
    Schema::new(columns.collect())
}

struct Db {
    storage: Storage,
    catalog: Arc<Catalog>,
    tm: TransactionManager,
}

impl Db {
    /// A new database with `t` and `rows` rows in it, all of it durable.
    fn create(fs: &CrashFs, frames: usize, segment: u64, rows: usize) -> Self {
        let storage = storage::open_with(Arc::new(fs.clone()), DB, frames, None, segment).unwrap();
        let catalog = Arc::new(Catalog::open(Arc::clone(&storage.bpm)).unwrap());
        let tm = TransactionManager::new(Arc::clone(&storage.bpm));
        let db = Self {
            storage,
            catalog,
            tm,
        };
        let txn = db.tm.begin();
        db.catalog
            .create_table_with_constraints(&txn, "t", t_schema(), &["id"], &["id"], &[])
            .unwrap();
        db.tm.commit(&txn).unwrap();
        for chunk in 0..rows.div_ceil(50) {
            let txn = db.tm.begin();
            for i in chunk * 50..rows.min(chunk * 50 + 50) {
                let v = (i % 40) as i32;
                assert!(db.insert(&txn, "t", |id| t_row(id, v, i % 150)).is_some());
            }
            db.tm.commit(&txn).unwrap();
        }
        db.storage.bpm.checkpoint().unwrap();
        db
    }

    /// Opens the database in `fs`, recovering it, and checks that its Tids
    /// start above every Tid the log ever held.
    fn open(fs: &CrashFs, frames: usize) -> Self {
        let storage = storage::open_with(Arc::new(fs.clone()), DB, frames, None, SEGMENT)
            .unwrap_or_else(|e| panic!("recovery failed: {e}"));
        let catalog = Catalog::open(Arc::clone(&storage.bpm))
            .unwrap_or_else(|e| panic!("the catalog does not open: {e}"));
        let tm = TransactionManager::new(Arc::clone(&storage.bpm));
        let (_, max_tid) = commits_in(fs);
        let next_tid = tm.next_tid();
        assert!(
            next_tid > max_tid,
            "Tids start at {next_tid}, but the log holds {max_tid}"
        );
        Self {
            storage,
            catalog: Arc::new(catalog),
            tm,
        }
    }

    fn table(&self, name: &str) -> Arc<TableInfo> {
        self.catalog.get_table(name).unwrap()
    }

    fn indexed(&self, table: &TableInfo) -> Arc<IndexedTable> {
        let pk = self
            .catalog
            .primary_key_index(table.oid)
            .map(|index| Arc::clone(&index.index));
        let heap = Arc::clone(&table.heap);
        Arc::new(IndexedTable::new(heap, table.schema.clone(), pk))
    }

    /// Inserts into `table`, in `txn`, the row `row` makes of the next id
    /// of its identity column, with its index entries, as INSERT does.
    /// Returns the row, or `None` if a unique key was taken.
    fn insert(
        &self,
        txn: &Transaction,
        table: &str,
        row: impl FnOnce(i64) -> Vec<Value>,
    ) -> Option<Vec<Value>> {
        let table = self.table(table);
        self.catalog
            .lock_table(txn, table.oid, LockMode::RowExclusive)
            .unwrap();
        let _writes = table.lock_writes();
        let mut indexes = self.catalog.table_indexes(&table.name);
        indexes.sort_by_key(|index| !index.kind.is_primary_key());
        let id = table.identity(0).unwrap().next_value().unwrap();
        let values = row(id);
        let tuple = Tuple::encode(&table.schema, &values).unwrap();
        let rid = txn.insert(&table.heap, &table.schema, &tuple).unwrap();
        let indexed = self.indexed(&table);
        for index in &indexes {
            let key = key_of(&table, index, &tuple);
            let locator = self.locator_of(&table, index, rid, &tuple);
            if !txn
                .insert_entry(&indexed, &index.index, &key, &locator, rid)
                .unwrap()
            {
                return None;
            }
        }
        Some(values)
    }

    /// What an entry of `index`, one of `table`'s, for the row `tuple` at
    /// `rid` leads to.
    fn locator_of(
        &self,
        table: &TableInfo,
        index: &IndexInfo,
        rid: Rid,
        tuple: &Tuple,
    ) -> RowLocator {
        match index.locator {
            LocatorKind::Rid => RowLocator::Rid(rid),
            LocatorKind::PrimaryKey => {
                let pk = self.catalog.primary_key_index(table.oid).unwrap();
                RowLocator::PrimaryKey(key_of(table, &pk, tuple))
            }
        }
    }

    /// Creates an index of `kind` on `key` of `table` in `txn`, filled from
    /// the table's rows, as CREATE INDEX does.
    fn create_index(
        &self,
        txn: &Transaction,
        name: &str,
        table: &str,
        key: &[&str],
        kind: IndexKind,
    ) -> catalog::Result<Arc<IndexInfo>> {
        self.catalog
            .create_index_with(txn, name, table, key, kind, |table, index| {
                match txn.build_index(&self.indexed(table), index)? {
                    Some(_) => Err(CatalogError::IndexExists(format!(
                        "a key of {name} repeats"
                    ))),
                    None => Ok(()),
                }
            })
    }
}

fn t_row(id: i64, v: i32, pad: usize) -> Vec<Value> {
    vec![
        Value::BigInt(id),
        Value::Int(v),
        Value::from("p".repeat(pad)),
    ]
}

fn u_row(id: i64, name: &str, k: i32) -> Vec<Value> {
    vec![Value::Int(id as i32), Value::from(name), Value::Int(k)]
}

fn key_of(table: &TableInfo, index: &IndexInfo, tuple: &Tuple) -> Tuple {
    tuple
        .to_key(&table.schema, &index.key_schema, &index.key_columns)
        .unwrap()
}

/// What a create made.
#[derive(Clone, Copy, Debug, PartialEq)]
enum Made {
    Table,
    Index,
}

/// A row's values, written out to compare.
type Row = String;

fn row_of(values: &[Value]) -> Row {
    format!("{values:?}")
}

#[derive(Clone, Default)]
struct Expect {
    /// The fs events, and the end of the log, once `t` was durable.
    setup: (usize, Lsn),
    /// Each create, with its transaction.
    creates: Vec<(String, Made, TxnId)>,
    /// The rows each transaction inserted, with their table.
    rows: HashMap<TxnId, Vec<(String, Row)>>,
    /// Each commit, with the number of fs events when it returned.
    acked: Vec<(TxnId, usize)>,
}

/// CREATE TABLE and CREATE INDEX over a table of `rows` rows, interleaved
/// with inserts: creates that commit, one whose build fails, and two left
/// open at the end, after their records reach the log.
fn run_workload(fs: &CrashFs, frames: usize, segment: u64, checkpoints: bool) -> (Db, Expect) {
    let db = Db::create(fs, frames, segment, 120);
    let mut expect = Expect {
        setup: (fs.num_events(), db.storage.bpm.log().end()),
        ..Expect::default()
    };
    let commit = |db: &Db, expect: &mut Expect, txn: &Transaction| {
        db.tm.commit(txn).unwrap();
        expect.acked.push((txn.tid(), fs.num_events()));
    };

    let txn = db.tm.begin();
    let unique = UniqueKey {
        name: None,
        columns: vec!["name".to_owned()],
        nulls_distinct: true,
    };
    db.catalog
        .create_table_with_constraints(&txn, "u", u_schema(), &["id"], &["id"], &[unique])
        .unwrap();
    expect
        .creates
        .push(("u".to_owned(), Made::Table, txn.tid()));
    commit(&db, &mut expect, &txn);

    let insert_u = |db: &Db, expect: &mut Expect, n: usize, tag: &str| {
        for i in 0..n {
            let txn = db.tm.begin();
            let row = db
                .insert(&txn, "u", |id| {
                    u_row(id, &format!("{tag}{i}"), (i % 7) as i32)
                })
                .unwrap();
            expect
                .rows
                .insert(txn.tid(), vec![("u".to_owned(), row_of(&row))]);
            commit(db, expect, &txn);
        }
    };
    insert_u(&db, &mut expect, 30, "a");
    for i in 0..6 {
        let txn = db.tm.begin();
        let name = format!("burst_{i}");
        db.catalog
            .create_table_with_constraints(&txn, &name, u_schema(), &["id"], &["id"], &[])
            .unwrap();
        expect.creates.push((name, Made::Table, txn.tid()));
        commit(&db, &mut expect, &txn);
    }
    if checkpoints {
        checkpoint::fuzzy(&db.storage.bpm).unwrap();
    }

    let txn = db.tm.begin();
    db.create_index(&txn, "t_v", "t", &["v"], IndexKind::Plain)
        .unwrap();
    expect
        .creates
        .push(("t_v".to_owned(), Made::Index, txn.tid()));
    commit(&db, &mut expect, &txn);

    // `v` repeats, so the build fails, after filling most of the tree.
    let txn = db.tm.begin();
    let unique = IndexKind::Unique {
        nulls_distinct: true,
    };
    assert!(
        db.create_index(&txn, "t_v_key", "t", &["v"], unique)
            .is_err()
    );
    expect
        .creates
        .push(("t_v_key".to_owned(), Made::Index, txn.tid()));
    db.tm.abort(&txn).unwrap();

    let txn = db.tm.begin();
    db.create_index(&txn, "u_k", "u", &["k"], IndexKind::Plain)
        .unwrap();
    expect
        .creates
        .push(("u_k".to_owned(), Made::Index, txn.tid()));
    commit(&db, &mut expect, &txn);
    if checkpoints {
        db.storage.bpm.checkpoint().unwrap();
    }

    // Left open: a table that spills the catalog onto a new page, and an
    // index on `t`, each in its own transaction.
    let wide = db.tm.begin();
    db.catalog
        .create_table(&wide, "wide", wide_schema(), &["column_00"])
        .unwrap();
    expect
        .creates
        .push(("wide".to_owned(), Made::Table, wide.tid()));
    insert_u(&db, &mut expect, 5, "b");
    let pad = db.tm.begin();
    db.create_index(&pad, "t_pad", "t", &["pad"], IndexKind::Plain)
        .unwrap();
    expect
        .creates
        .push(("t_pad".to_owned(), Made::Index, pad.tid()));
    db.storage.bpm.log().flush_all().unwrap();
    std::mem::forget((wide, pad));
    (db, expect)
}

/// The Tids whose `Commit` is in `fs`'s log, every segment it ever had, and
/// the highest Tid of any record.
fn commits_in(fs: &CrashFs) -> (HashSet<TxnId>, TxnId) {
    let log = Log::open(Arc::new(fs.with_removed()), LOG, SEGMENT).unwrap();
    let (mut commits, mut max_tid) = (HashSet::new(), INVALID_TXN_ID);
    let mut scan = log.scan(FIRST_LSN);
    while let Some(record) = scan.next_record().unwrap() {
        max_tid = max_tid.max(record.tid);
        if record.kind == Kind::Commit {
            commits.insert(record.tid);
        }
    }
    (commits, max_tid)
}

/// The rows of `table` a new transaction sees, with their rids.
fn visible(db: &Db, table: &TableInfo) -> Vec<(Rid, Tuple)> {
    let txn = db.tm.begin();
    let mut scan = txn.scan(&table.heap, &table.schema).unwrap();
    let mut rows = Vec::new();
    while let Some(batch) = scan.next_batch().unwrap() {
        rows.extend(
            batch
                .into_iter()
                .map(|(_, tuple)| (tuple.rid().unwrap(), tuple)),
        );
    }
    db.tm.commit(&txn).unwrap();
    rows
}

/// Every page with a place in the db file, after writing every page.
fn allocated(db: &Db) -> BTreeSet<PageId> {
    db.storage.bpm.checkpoint().unwrap();
    let disk = db.storage.bpm.disk_manager();
    (0..disk.next_page_id())
        .filter(|&page_id| disk.has_page(page_id))
        .collect()
}

/// Every page the catalog reaches: page 0, the system tables', and those of
/// every table, sequence and index.
fn reachable(db: &Db) -> BTreeSet<PageId> {
    let bpm = &db.storage.bpm;
    let roots = {
        let guard = bpm.read_page(CATALOG_PAGE_ID, AccessType::Unknown);
        SystemTableRoots::read_from(guard.get_data()).unwrap()
    };
    let mut pages = BTreeSet::from([CATALOG_PAGE_ID]);
    let system = [
        roots.tables,
        roots.columns,
        roots.indexes,
        roots.index_columns,
    ];
    for first in system {
        let heap = TableHeap::open(Arc::clone(bpm), first).unwrap();
        pages.extend(heap.page_ids().unwrap());
    }
    for table in db.catalog.tables() {
        pages.extend(table.heap.page_ids().unwrap());
        for sequence in table.sequences() {
            pages.extend(db.table(&sequence.name).heap.page_ids().unwrap());
        }
        for index in db.catalog.table_indexes(&table.name) {
            let Index::BtreeIndex(btree) = &*index.index;
            pages.extend(btree.tree().page_ids().unwrap());
        }
    }
    pages
}

/// Checks `db` against what the transactions in `committed` did: each
/// create is there exactly if it committed; each table holds exactly the
/// committed rows, each of its indexes an entry for every row and no
/// other, and its sequences hand out an id above every row's; every page
/// is one the catalog reaches; and a committed table takes new rows.
fn check(db: &Db, expect: &Expect, committed: &HashSet<TxnId>, at: &str) {
    for (name, made, tid) in &expect.creates {
        let there = match made {
            Made::Table => db.catalog.get_table(name).is_some(),
            Made::Index => db.catalog.get_index(name).is_some(),
        };
        assert_eq!(
            there,
            committed.contains(tid),
            "{at}: {made:?} {name}, created by {tid}, is there: {there}"
        );
    }
    let mut expected: BTreeMap<&str, BTreeSet<Row>> = BTreeMap::new();
    for (tid, rows) in &expect.rows {
        if committed.contains(tid) {
            for (table, row) in rows {
                expected.entry(table).or_default().insert(row.clone());
            }
        }
    }
    for table in db.catalog.tables() {
        let rows = visible(db, &table);
        if table.name != "t" {
            let seen: BTreeSet<Row> = rows
                .iter()
                .map(|(_, tuple)| row_of(&tuple.decode(&table.schema).unwrap()))
                .collect();
            let want = expected.remove(table.name.as_str()).unwrap_or_default();
            assert_eq!(seen, want, "{at}: rows of {}", table.name);
        } else {
            assert_eq!(rows.len(), 120, "{at}: rows of t");
        }
        for index in db.catalog.table_indexes(&table.name) {
            for (rid, tuple) in &rows {
                let mut found = Vec::new();
                index
                    .index
                    .scan_key(&key_of(&table, &index, tuple), &mut found)
                    .unwrap();
                let locator = db.locator_of(&table, &index, *rid, tuple);
                assert!(
                    found.contains(&locator),
                    "{at}: {} has no entry for the row at {rid}",
                    index.name
                );
            }
            let Index::BtreeIndex(btree) = &*index.index;
            let entries = btree.tree().begin().unwrap().count();
            assert_eq!(entries, rows.len(), "{at}: entries of {}", index.name);
        }
        for sequence in table.sequences() {
            let next = sequence.next_value().unwrap();
            let max = rows
                .iter()
                .map(|(_, tuple)| match tuple.decode(&table.schema).unwrap()[0] {
                    Value::Int(id) => i64::from(id),
                    Value::BigInt(id) => id,
                    ref other => panic!("{at}: id {other:?}"),
                })
                .max();
            assert!(
                max.is_none_or(|max| next > max),
                "{at}: {} hands out {next}, but a row of {} holds {max:?}",
                sequence.name,
                table.name
            );
        }
    }
    assert!(expected.is_empty(), "{at}: rows of a table that is gone");

    let reachable = reachable(db);
    let allocated = allocated(db);
    let leaked: Vec<_> = allocated.difference(&reachable).collect();
    let lost: Vec<_> = reachable.difference(&allocated).collect();
    assert!(
        leaked.is_empty() && lost.is_empty(),
        "{at}: pages nothing reaches {leaked:?}, pages reached but freed {lost:?}"
    );

    if db.catalog.get_table("u").is_some() {
        let txn = db.tm.begin();
        let row = db.insert(&txn, "u", |id| u_row(id, "after", 1));
        assert!(row.is_some(), "{at}: u takes no new row");
        db.tm.commit(&txn).unwrap();
    }
}

/// Recovers `image`, a crash after `events` fs events, and checks it.
fn recover_and_check(image: &CrashFs, events: usize, expect: &Expect, at: &str) {
    let (committed, _) = commits_in(image);
    for &(tid, acked_at) in &expect.acked {
        assert!(
            acked_at > events || committed.contains(&tid),
            "{at}: transaction {tid}, acknowledged after event {acked_at}, is lost"
        );
    }
    check(&Db::open(image, 8), expect, &committed, at);
}

#[test]
fn every_crash_point_keeps_exactly_the_committed_creates() {
    let fs = CrashFs::new();
    let (db, expect) = run_workload(&fs, 8, SEGMENT, true);
    drop(db);
    let mut crashes = 0;
    fs.for_each_moment(|n, moment| {
        if n < expect.setup.0 {
            return;
        }
        for lost in [Lost::Nothing, Lost::Everything, Lost::Some(n as u64)] {
            let at = format!("crash after event {n}, losing {lost:?}");
            recover_and_check(&moment.crash(lost), n, &expect, &at);
            crashes += 1;
        }
    });
    assert!(crashes > 450, "only {crashes} crash points");
}

/// Without page writes the log is all there is, so cutting it after any
/// record leaves each create in every state it passes through: storage
/// made, a sequence's row in, catalog rows part written, a build part
/// done, a rollback part done.
#[test]
fn every_prefix_of_the_log_keeps_the_creates_below_the_cut() {
    let fs = CrashFs::new();
    let (db, expect) = run_workload(&fs, 512, u64::MAX, false);
    drop(db);
    let segment = std::path::PathBuf::from(format!("{LOG}.{:08}", 1));
    let bytes = fs.contents(&segment);
    let log = Log::open(Arc::new(fs.crash_now()), LOG, u64::MAX).unwrap();
    let mut cuts = vec![log.end()];
    let mut scan = log.scan(expect.setup.1);
    while let Some(record) = scan.next_record().unwrap() {
        cuts.push(record.lsn);
    }
    assert!(cuts.len() > 100, "{} records", cuts.len());
    for cut in cuts {
        let image = fs.with_contents(&segment, &bytes[..cut as usize]);
        let (committed, _) = commits_in(&image);
        check(
            &Db::open(&image, 64),
            &expect,
            &committed,
            &format!("log cut at {cut}"),
        );
    }
}

/// A Tid that logged is never handed out again, even when every record
/// naming it comes before the checkpoint recovery starts from: a new
/// transaction would then read that one's committed rows as newer than
/// itself, and take a crashed one's rows for its own.
#[test]
fn tids_start_above_every_tid_that_logged() {
    let fs = CrashFs::new();
    let db = Db::create(&fs, 16, SEGMENT, 0);
    let insert = |txn: &Transaction, v: i32| {
        let row = db.insert(txn, "t", |id| t_row(id, v, 10)).unwrap();
        row_of(&row)
    };
    let first = db.tm.begin();
    let mut committed = BTreeSet::from([insert(&first, 1)]);
    db.tm.commit(&first).unwrap();
    let open = db.tm.begin();
    insert(&open, 2);
    let last = db.tm.begin();
    committed.insert(insert(&last, 3));
    db.tm.commit(&last).unwrap();
    // Recovery reads no record after this, and `open` goes on in its table.
    checkpoint::fuzzy(&db.storage.bpm).unwrap();
    std::mem::forget(open);
    let newest = last.tid();
    drop((first, last, db));

    let db = Db::open(&fs.crash_after(fs.num_events(), Lost::Nothing), 16);
    let txn = db.tm.begin();
    assert!(txn.tid() > newest, "Tid {} again", txn.tid());
    db.tm.commit(&txn).unwrap();
    let t = db.table("t");
    let rows: BTreeSet<Row> = visible(&db, &t)
        .into_iter()
        .map(|(_, tuple)| row_of(&tuple.decode(&t.schema).unwrap()))
        .collect();
    assert_eq!(rows, committed);
    let rows = visible(&db, &t);
    let txn = db.tm.begin();
    for (rid, tuple) in rows {
        txn.update(&t.heap, &t.schema, rid, &tuple)
            .unwrap_or_else(|e| panic!("the row at {rid} is not writable: {e}"));
    }
    db.tm.commit(&txn).unwrap();
}

/// No crash makes a sequence hand out an id a committed row holds, though
/// each round starts from what the last crash left, and RESTART IDENTITY
/// commits and rolls back in between.
#[test]
fn a_sequence_never_hands_out_a_committed_id_across_crashes() {
    let mut fs = CrashFs::new();
    let mut db = Db::create(&fs, 8, SEGMENT, 0);
    let mut rng = 0x5e9u64;
    let mut below = |n: usize| next(&mut rng) as usize % n;
    let (mut restarts, mut rollbacks) = (0, 0);
    for round in 0..14 {
        let start = fs.num_events();
        for _ in 0..12 {
            let txn = db.tm.begin();
            let truncate = below(3) == 0;
            if truncate {
                let oid = db.table("t").oid;
                db.catalog
                    .lock_table(&txn, oid, LockMode::AccessExclusive)
                    .unwrap();
                db.catalog.truncate(&txn, oid, true).unwrap();
            }
            for _ in 0..below(40) {
                let row = db.insert(&txn, "t", |id| t_row(id, 0, 100));
                assert!(row.is_some(), "round {round}: an id was handed out twice");
            }
            match below(3) {
                0 => {
                    db.tm.abort(&txn).unwrap();
                    rollbacks += usize::from(truncate);
                }
                _ => {
                    db.tm.commit(&txn).unwrap();
                    restarts += usize::from(truncate);
                }
            }
        }
        let n = start + below(fs.num_events() - start + 1);
        let lost = match below(3) {
            0 => Lost::Nothing,
            1 => Lost::Everything,
            _ => Lost::Some(n as u64),
        };
        drop(db);
        fs = fs.crash_after(n, lost);
        db = Db::open(&fs, 8);
        let t = db.table("t");
        let max = visible(&db, &t)
            .into_iter()
            .map(|(_, tuple)| match tuple.decode(&t.schema).unwrap()[0] {
                Value::BigInt(id) => id,
                ref other => panic!("id {other:?}"),
            })
            .max();
        let next = t.identity(0).unwrap().next_value().unwrap();
        assert!(
            max.is_none_or(|max| next > max),
            "round {round}, crash after event {n} losing {lost:?}: next id {next}, but a row holds {max:?}"
        );
    }
    assert!(
        restarts >= 3 && rollbacks >= 3,
        "{restarts} restarts, {rollbacks} rolled back"
    );
}
