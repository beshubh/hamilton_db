//! Crash recovery of CREATE TABLE and CREATE INDEX, and of the counters a
//! crash must not hand out again. Whatever moment a crash comes at, and
//! whatever unsynced writes it loses or tears, each create whose `Commit`
//! reached the log is whole and works, every acknowledged one among them,
//! and each other create left nothing: no catalog row, and no page the
//! catalog does not reach. Tids start above every Tid in the log, and no
//! sequence hands out an id a committed row holds.

#[path = "../../storage/tests/util/crash_fs.rs"]
mod crash_fs;

