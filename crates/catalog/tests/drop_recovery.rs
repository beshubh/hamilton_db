//! Crash recovery of DROP TABLE. Whatever moment a crash comes at, and
//! whatever unsynced writes it loses or tears, the table exists after
//! recovery exactly when the last create or drop of it whose `Commit`
//! reached the log is a create, every acknowledged commit among them. A
//! table that exists has its rows, its index entries and a sequence that
//! goes on past every id; one that does not leaves its names free; and no
//! page is allocated that the catalog does not reach.

#[path = "../../storage/tests/util/crash_fs.rs"]
mod crash_fs;

use std::collections::{BTreeMap, BTreeSet, HashMap};
use std::sync::Arc;

use catalog::header_page::{CATALOG_PAGE_ID, SystemTableRoots};
use catalog::{Catalog, IndexInfo, LockMode};
use common::{Column, DataType, Lsn, PageId, Rid, Schema, Tuple, TxnId, Value};
use crash_fs::{CrashFs, Lost};
use storage::Storage;
use storage::buffer::arc_replacer::AccessType;
use storage::concurrency::index_versions::IndexedTable;
use storage::concurrency::transaction::Transaction;
use storage::concurrency::transaction_manager::TransactionManager;
use storage::index::{Index, IndexTrait, RowLocator};
use storage::table::table_heap::TableHeap;
use storage::wal::checkpoint;
use storage::wal::log::{FIRST_LSN, Log};
use storage::wal::record::Kind;

const DB: &str = "/db/test.db";
const LOG: &str = "/db/test.log";

/// Small, so the workload starts and removes segments.
const SEGMENT: u64 = 32 << 10;

/// `t (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, v INT,
/// pad VARCHAR(200))`, with an index `t_v` on `v` that stores primary keys.
fn schema() -> Schema {
    Schema::new(vec![
        Column::new("id", DataType::BigInt, false),
        Column::new("v", DataType::Int, true),
        Column::new("pad", DataType::Varchar(200), true),
    ])
}

fn key(index: &IndexInfo, value: Value) -> Tuple {
    Tuple::encode(&index.key_schema, &[value]).unwrap()
}

struct Db {
    storage: Storage,
    catalog: Arc<Catalog>,
    tm: TransactionManager,
}

impl Db {
    fn open(fs: &CrashFs, frames: usize, segment: u64) -> Self {
        let storage = storage::open_with(Arc::new(fs.clone()), DB, frames, None, segment)
            .unwrap_or_else(|e| panic!("recovery failed: {e}"));
        let catalog = Catalog::open(Arc::clone(&storage.bpm))
            .unwrap_or_else(|e| panic!("the catalog does not open: {e}"));
        let tm = TransactionManager::new(Arc::clone(&storage.bpm));
        Self {
            storage,
            catalog: Arc::new(catalog),
            tm,
        }
    }

    /// Creates `t` and `t_v` in `txn`, as CREATE TABLE and CREATE INDEX do,
    /// and `u`, which is dropped with `t`.
    fn create(&self, txn: &Transaction) {
        self.catalog
            .create_table_with_constraints(txn, "t", schema(), &["id"], &["id"], &[])
            .unwrap();
        self.catalog.create_index(txn, "t_v", "t", &["v"]).unwrap();
        let u = Schema::new(vec![Column::new("id", DataType::Int, false)]);
        self.catalog.create_table(txn, "u", u, &["id"]).unwrap();
    }

    /// Drops `t` and `u` in `txn`, as `DROP TABLE t, u` does.
    fn drop_t(&self, txn: &Transaction) {
        for name in ["t", "u"] {
            let oid = self.catalog.get_table(name).unwrap().oid;
            self.catalog
                .lock_table(txn, oid, LockMode::AccessExclusive)
                .unwrap();
            self.catalog.drop_table(txn, oid).unwrap();
        }
    }

    /// Inserts `n` rows into `t` in `txn`, with their index entries, as
    /// INSERT does, and returns each row's id and `v`.
    fn insert(&self, txn: &Transaction, n: i32) -> Vec<(i64, i32)> {
        let table = self.catalog.get_table("t").unwrap();
        self.catalog
            .lock_table(txn, table.oid, LockMode::RowExclusive)
            .unwrap();
        let indexes = self.catalog.table_indexes("t");
        let (pk, by_v) = (&indexes[0], &indexes[1]);
        let heap = Arc::clone(&table.heap);
        let indexed = IndexedTable::new(heap, table.schema.clone(), Some(Arc::clone(&pk.index)));
        let indexed = Arc::new(indexed);
        let mut rows = Vec::new();
        for v in 0..n {
            let id = table.identity(0).unwrap().next_value().unwrap();
            let values = [
                Value::BigInt(id),
                Value::Int(v),
                Value::from("p".repeat(200)),
            ];
            let tuple = Tuple::encode(&table.schema, &values).unwrap();
            let rid = txn.insert(&table.heap, &table.schema, &tuple).unwrap();
            let pk_key = key(pk, Value::BigInt(id));
            let by_pk = RowLocator::PrimaryKey(pk_key.clone());
            let v_key = key(by_v, Value::Int(v));
            assert!(
                txn.insert_entry(&indexed, &pk.index, &pk_key, &RowLocator::Rid(rid), rid)
                    .unwrap()
                    && txn
                        .insert_entry(&indexed, &by_v.index, &v_key, &by_pk, rid)
                        .unwrap()
            );
            rows.push((id, v));
        }
        rows
    }
}

/// What a transaction did to `t`.
enum Step {
    Create,
    Insert(Vec<(i64, i32)>),
    Drop,
}

/// What the workload did, which decides what a crash must leave.
#[derive(Default)]
struct Expect {
    steps: HashMap<TxnId, Step>,
    /// Each commit, with the number of fs events when it returned.
    acked: Vec<(TxnId, usize)>,
    /// The fs events and the log's end once the first `t` was durable.
    setup: (usize, Lsn),
}

struct Workload<'a> {
    fs: &'a CrashFs,
    db: Db,
    expect: Expect,
}

impl Workload<'_> {
    /// Runs `step` in a new transaction, then commits it.
    fn commit(&mut self, step: impl FnOnce(&Db, &Transaction) -> Step) {
        let txn = self.db.tm.begin();
        let step = step(&self.db, &txn);
        self.db.tm.commit(&txn).unwrap();
        self.expect.acked.push((txn.tid(), self.fs.num_events()));
        self.expect.steps.insert(txn.tid(), step);
    }
}

/// Creates and fills `t`, then drops it: once rolled back, once committed
/// while a reader holds back the free, and once left running at the crash,
/// after `t` is made again under the same names. With `checkpoints`, the
/// uncommitted drops reach the db file and a checkpoint lands between a
/// commit and its free.
fn run_workload(fs: &CrashFs, frames: usize, segment: u64, checkpoints: bool) -> Expect {
    let db = Db::open(fs, frames, segment);
    let mut w = Workload {
        fs,
        db,
        expect: Expect::default(),
    };
    w.commit(|db, txn| {
        db.create(txn);
        Step::Create
    });
    w.commit(|db, txn| Step::Insert(db.insert(txn, 60)));
    w.db.storage.bpm.checkpoint().unwrap();
    w.expect.setup = (fs.num_events(), w.db.storage.bpm.log().end());

    let txn = w.db.tm.begin();
    w.db.drop_t(&txn);
    if checkpoints {
        w.db.storage.bpm.checkpoint().unwrap();
    }
    w.db.tm.abort(&txn).unwrap();

    let reader = w.db.tm.begin();
    w.commit(|db, txn| {
        db.drop_t(txn);
        Step::Drop
    });
    if checkpoints {
        checkpoint::fuzzy(&w.db.storage.bpm).unwrap();
    }
    w.db.tm.abort(&reader).unwrap();
    w.db.tm.wait_for_gc();

    w.commit(|db, txn| {
        db.create(txn);
        Step::Create
    });
    w.commit(|db, txn| Step::Insert(db.insert(txn, 60)));
    let txn = w.db.tm.begin();
    w.db.drop_t(&txn);
    match checkpoints {
        true => w.db.storage.bpm.checkpoint().unwrap(),
        false => w.db.storage.bpm.log().flush_all().unwrap(),
    }
    std::mem::forget(txn);
    w.expect
}

/// The Tids whose `Commit` is in `fs`'s log, every segment it ever had, in
/// log order.
fn commits_in(fs: &CrashFs) -> Vec<TxnId> {
    let log = Log::open(Arc::new(fs.with_removed()), LOG, SEGMENT).unwrap();
    let mut commits = Vec::new();
    let mut scan = log.scan(FIRST_LSN);
    while let Some(record) = scan.next_record().unwrap() {
        if record.kind == Kind::Commit {
            commits.push(record.tid);
        }
    }
    commits
}

/// The rows of `t`, by id, that `commits` leave, or `None` if they leave
/// no `t`.
fn rows_after(expect: &Expect, commits: &[TxnId]) -> Option<BTreeMap<i64, i32>> {
    let mut t = None;
    for tid in commits {
        match expect.steps.get(tid) {
            Some(Step::Create) => t = Some(BTreeMap::new()),
            Some(Step::Insert(rows)) => t.as_mut().unwrap().extend(rows.iter().copied()),
            Some(Step::Drop) => t = None,
            None => {}
        }
    }
    t
}

/// Every page with a place in the db file, after writing every page.
fn allocated(db: &Db) -> BTreeSet<PageId> {
    db.storage.bpm.checkpoint().unwrap();
    let disk = db.storage.bpm.disk_manager();
    (0..disk.next_page_id())
        .filter(|&page_id| disk.has_page(page_id))
        .collect()
}

/// Every page the catalog reaches: page 0, the system tables', and those of
/// every table, sequence and index.
fn reachable(db: &Db) -> BTreeSet<PageId> {
    let bpm = &db.storage.bpm;
    let roots = {
        let guard = bpm.read_page(CATALOG_PAGE_ID, AccessType::Unknown);
        SystemTableRoots::read_from(guard.get_data()).unwrap()
    };
    let mut pages = BTreeSet::from([CATALOG_PAGE_ID]);
    let system = [
        roots.tables,
        roots.columns,
        roots.indexes,
        roots.index_columns,
    ];
    for first in system {
        let heap = TableHeap::open(Arc::clone(bpm), first).unwrap();
        pages.extend(heap.page_ids().unwrap());
    }
    for table in db.catalog.tables() {
        pages.extend(table.heap.page_ids().unwrap());
        for sequence in table.sequences() {
            let relation = db.catalog.get_table(&sequence.name).unwrap();
            pages.extend(relation.heap.page_ids().unwrap());
        }
        for index in db.catalog.table_indexes(&table.name) {
            let Index::BtreeIndex(btree) = &*index.index;
            pages.extend(btree.tree().page_ids().unwrap());
        }
    }
    pages
}

/// The rows of `t` a new transaction sees, by id, with `v` and the rid.
fn visible(db: &Db) -> BTreeMap<i64, (i32, Rid)> {
    let table = db.catalog.get_table("t").unwrap();
    let txn = db.tm.begin();
    let mut scan = txn.scan(&table.heap, &table.schema).unwrap();
    let mut rows = BTreeMap::new();
    while let Some(batch) = scan.next_batch().unwrap() {
        for (_, tuple) in batch {
            let values = tuple.decode(&table.schema).unwrap();
            let [Value::BigInt(id), Value::Int(v), _] = &values[..] else {
                panic!("bad row {values:?}");
            };
            rows.insert(*id, (*v, tuple.rid().unwrap()));
        }
    }
    db.tm.commit(&txn).unwrap();
    rows
}

/// Checks that every page is one the catalog reaches, and that `t` is
/// there exactly when `expected` is: with those rows, an index entry for
/// each, and a sequence past every id. Without it, `t` is made again.
fn check(db: &Db, expected: Option<&BTreeMap<i64, i32>>, at: &str) {
    let (reachable, allocated) = (reachable(db), allocated(db));
    let leaked: Vec<_> = allocated.difference(&reachable).collect();
    let lost: Vec<_> = reachable.difference(&allocated).collect();
    assert!(
        leaked.is_empty() && lost.is_empty(),
        "{at}: pages nothing reaches {leaked:?}, pages reached but freed {lost:?}"
    );

    let u = db.catalog.get_table("u").is_some();
    assert_eq!(u, expected.is_some(), "{at}: u is dropped apart from t");
    let Some(expected) = expected else {
        assert!(db.catalog.get_table("t").is_none(), "{at}: t is there");
        let txn = db.tm.begin();
        db.create(&txn);
        db.tm.commit(&txn).unwrap();
        return;
    };
    let table = db
        .catalog
        .get_table("t")
        .unwrap_or_else(|| panic!("{at}: t is gone"));
    let rows = visible(db);
    let seen: BTreeMap<i64, i32> = rows.iter().map(|(&id, &(v, _))| (id, v)).collect();
    assert_eq!(&seen, expected, "{at}: rows");
    let indexes = db.catalog.table_indexes("t");
    let (pk, by_v) = (&indexes[0], &indexes[1]);
    for (&id, &(v, rid)) in &rows {
        let mut found = Vec::new();
        pk.index
            .scan_key(&key(pk, Value::BigInt(id)), &mut found)
            .unwrap();
        assert_eq!(found, [RowLocator::Rid(rid)], "{at}: key entry of row {id}");
        found.clear();
        by_v.index
            .scan_key(&key(by_v, Value::Int(v)), &mut found)
            .unwrap();
        let by_pk = RowLocator::PrimaryKey(key(pk, Value::BigInt(id)));
        assert!(found.contains(&by_pk), "{at}: no v entry for row {id}");
    }
    let next = table.identity(0).unwrap().next_value().unwrap();
    if let Some((&max, _)) = rows.last_key_value() {
        assert!(
            next > max,
            "{at}: the sequence hands out {next} after {max}"
        );
    }
}

/// Recovers `image`, a crash after `events` fs events, and checks it.
fn recover_and_check(image: &CrashFs, events: usize, expect: &Expect, at: &str) {
    let commits = commits_in(image);
    for &(tid, acked_at) in &expect.acked {
        assert!(
            acked_at > events || commits.contains(&tid),
            "{at}: transaction {tid}, acknowledged after event {acked_at}, is lost"
        );
    }
    let db = Db::open(image, 8, SEGMENT);
    check(&db, rows_after(expect, &commits).as_ref(), at);
}

#[test]
fn every_crash_point_keeps_exactly_the_committed_drops() {
    let fs = CrashFs::new();
    let expect = run_workload(&fs, 6, SEGMENT, true);
    let mut crashes = 0;
    fs.for_each_moment(|n, moment| {
        if n < expect.setup.0 {
            return;
        }
        for lost in [Lost::Nothing, Lost::Everything, Lost::Some(n as u64)] {
            let at = format!("crash after event {n}, losing {lost:?}");
            recover_and_check(&moment.crash(lost), n, &expect, &at);
            crashes += 1;
        }
    });
    assert!(crashes > 150, "only {crashes} crash points");
}

/// Without page writes the log is all there is, so cutting it after any
/// record leaves each drop in every state it passes through: catalog rows
/// part deleted, storage given up, committed with its storage not yet
/// freed, freed with no `End`, its undo part done.
#[test]
fn every_prefix_of_the_log_keeps_the_drops_below_the_cut() {
    let fs = CrashFs::new();
    let expect = run_workload(&fs, 512, u64::MAX, false);
    let segment = std::path::PathBuf::from(format!("{LOG}.{:08}", 1));
    let bytes = fs.contents(&segment);
    let log = Log::open(Arc::new(fs.crash_now()), LOG, u64::MAX).unwrap();
    let mut cuts = vec![log.end()];
    let mut scan = log.scan(expect.setup.1);
    while let Some(record) = scan.next_record().unwrap() {
        cuts.push(record.lsn);
    }
    assert!(cuts.len() > 50, "{} records", cuts.len());
    for cut in cuts {
        let image = fs.with_contents(&segment, &bytes[..cut as usize]);
        let commits = commits_in(&image);
        let db = Db::open(&image, 64, SEGMENT);
        check(
            &db,
            rows_after(&expect, &commits).as_ref(),
            &format!("log cut at {cut}"),
        );
    }
}
