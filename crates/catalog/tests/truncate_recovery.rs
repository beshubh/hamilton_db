//! Crash recovery of TRUNCATE. Whatever moment a crash comes at, and
//! whatever unsynced writes it loses or tears, the database that opens
//! again holds the table as exactly the transactions whose `Commit` reached
//! the log left it, every acknowledged commit among them, with or without
//! RESTART IDENTITY; its indexes hold an entry for every row and none
//! outside its heap; no page is allocated that nothing reaches; and its
//! sequence hands out no id a row holds.

#[path = "../../storage/tests/util/crash_fs.rs"]
mod crash_fs;

use std::collections::{BTreeMap, BTreeSet, HashMap, HashSet};
use std::sync::Arc;

use catalog::{Catalog, CatalogError, IndexInfo, LockMode, TableInfo};
use common::{Column, DataType, INVALID_TXN_ID, PageId, Rid, Schema, TXN_UNCOMMITTED_BIT, Tuple};
use common::{TxnId, Value};
use crash_fs::{CrashFs, Lost, next};
use storage::Storage;
use storage::buffer::arc_replacer::AccessType;
use storage::concurrency::index_versions::IndexedTable;
use storage::concurrency::transaction::Transaction;
use storage::concurrency::transaction_manager::TransactionManager;
use storage::index::{Index, IndexTrait, RowLocator};
use storage::table::table_page::TablePage;
use storage::wal::checkpoint;
use storage::wal::log::{FIRST_LSN, Log};
use storage::wal::record::Kind;

const DB: &str = "/db/test.db";
const LOG: &str = "/db/test.log";

/// Small, so the workloads start and remove segments.
const SEGMENT: u64 = 32 << 10;

/// `t (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, v INT,
/// pad VARCHAR(300))`, with an index `t_v` on `v` that stores primary keys.
fn schema() -> Schema {
    Schema::new(vec![
        Column::new("id", DataType::BigInt, false),
        Column::new("v", DataType::Int, true),
        Column::new("pad", DataType::Varchar(300), true),
    ])
}

/// A row's value and pad length.
type Row = (i32, usize);

fn encode(id: i64, (v, pad): Row) -> Tuple {
    let values = [
        Value::BigInt(id),
        Value::Int(v),
        Value::from("p".repeat(pad)),
    ];
    Tuple::encode(&schema(), &values).unwrap()
}

fn key(index: &IndexInfo, value: Value) -> Tuple {
    Tuple::encode(&index.key_schema, &[value]).unwrap()
}

struct Db {
    storage: Storage,
    catalog: Arc<Catalog>,
    tm: TransactionManager,
}

impl Db {
    /// A new database with `t` and its indexes, all of it durable, whose
    /// log starts a segment once the last holds `segment` bytes.
    fn create(fs: &CrashFs, frames: usize, segment: u64) -> Self {
        let storage = storage::open_with(Arc::new(fs.clone()), DB, frames, None, segment).unwrap();
        let catalog = Arc::new(Catalog::open(Arc::clone(&storage.bpm)).unwrap());
        let tm = TransactionManager::new(Arc::clone(&storage.bpm));
        let txn = tm.begin();
        catalog
            .create_table_with_constraints(&txn, "t", schema(), &["id"], &["id"], &[])
            .unwrap();
        tm.commit(&txn).unwrap();
        let txn = tm.begin();
        catalog.create_index(&txn, "t_v", "t", &["v"]).unwrap();
        tm.commit(&txn).unwrap();
        storage.bpm.checkpoint().unwrap();
        Self {
            storage,
            catalog,
            tm,
        }
    }

    /// Opens the database in `fs`, recovering it, and checks that its Tids
    /// start above every Tid the log ever held.
    fn open(fs: &CrashFs, frames: usize) -> Self {
        let storage = storage::open_with(Arc::new(fs.clone()), DB, frames, None, SEGMENT)
            .unwrap_or_else(|e| panic!("recovery failed: {e}"));
        let catalog = Arc::new(Catalog::open(Arc::clone(&storage.bpm)).unwrap());
        let tm = TransactionManager::new(Arc::clone(&storage.bpm));
        let (_, max_tid) = commits_in(fs);
        let next_tid = tm.next_tid();
        assert!(
            next_tid > max_tid,
            "Tids start at {next_tid}, but the log holds {max_tid}"
        );
        Self {
            storage,
            catalog,
            tm,
        }
    }

    fn table(&self) -> Arc<TableInfo> {
        self.catalog.get_table("t").unwrap()
    }

    /// `t_pkey`, then `t_v`.
    fn indexes(&self) -> Vec<Arc<IndexInfo>> {
        self.catalog.table_indexes("t")
    }

    fn indexed(&self, table: &TableInfo) -> Arc<IndexedTable> {
        let pk = Arc::clone(&self.indexes()[0].index);
        let heap = Arc::clone(&table.heap);
        Arc::new(IndexedTable::new(heap, table.schema.clone(), Some(pk)))
    }

    /// Every page with a place in the db file, after writing every page.
    fn allocated(&self) -> BTreeSet<PageId> {
        self.storage.bpm.checkpoint().unwrap();
        let disk = self.storage.bpm.disk_manager();
        (0..disk.next_page_id())
            .filter(|&page_id| disk.has_page(page_id))
            .collect()
    }

    /// Every page of `t`, its indexes and its sequence.
    fn reachable(&self) -> BTreeSet<PageId> {
        let mut pages: BTreeSet<_> = self.table().heap.page_ids().unwrap().into_iter().collect();
        for index in self.indexes() {
            let Index::BtreeIndex(btree) = &*index.index;
            pages.extend(btree.tree().page_ids().unwrap());
        }
        let sequence = self.catalog.get_table("t_id_seq").unwrap();
        pages.extend(sequence.heap.page_ids().unwrap());
        pages
    }
}

/// What a committed transaction left: whether it truncated `t`, and then
/// each row it wrote, or nothing for a delete.
#[derive(Clone, Default)]
struct Effects {
    truncated: bool,
    rows: BTreeMap<i64, Option<Row>>,
}

/// A transaction the workload has open, with the rows it wrote as it sees
/// them: each row's value and rid, or `None` once deleted.
struct Open {
    txn: Arc<Transaction>,
    effects: Effects,
    rids: HashMap<i64, Rid>,
}

/// What the workload did, which decides what a crash must leave.
#[derive(Clone, Default)]
struct Expect {
    effects: HashMap<TxnId, Effects>,
    /// Each commit, with the number of fs events when it returned.
    acked: Vec<(TxnId, usize)>,
    /// The pages of the catalog itself, which no truncate changes.
    system: BTreeSet<PageId>,
}

/// Transactions that insert, update, delete and truncate `t`, interleaved
/// on one thread, through table locks as statements take them. They
/// commit, abort, or are still open at the end, and a pool too small for
/// the table writes pages before their changes commit.
struct Workload {
    fs: CrashFs,
    db: Db,
    /// The fs events once the table was durable.
    setup: usize,
    rng: u64,
    committed: BTreeMap<i64, (Row, Rid)>,
    open: Vec<Open>,
    expect: Expect,
    /// Truncates rolled back.
    undone: usize,
}

impl Workload {
    fn new(fs: &CrashFs, frames: usize, seed: u64) -> Self {
        Self::with_segment(fs, frames, SEGMENT, seed)
    }

    fn with_segment(fs: &CrashFs, frames: usize, segment: u64, seed: u64) -> Self {
        let db = Db::create(fs, frames, segment);
        let reachable = db.reachable();
        let system = db.allocated().difference(&reachable).copied().collect();
        Self {
            fs: fs.clone(),
            db,
            setup: fs.num_events(),
            rng: seed,
            committed: BTreeMap::new(),
            open: Vec::new(),
            expect: Expect {
                system,
                ..Expect::default()
            },
            undone: 0,
        }
    }

    fn below(&mut self, n: usize) -> usize {
        next(&mut self.rng) as usize % n.max(1)
    }

    fn run(&mut self, steps: usize) {
        for _ in 0..steps {
            match self.below(24) {
                _ if self.open.is_empty() => {
                    self.begin();
                }
                0..=2 if self.open.len() < 3 => {
                    self.begin();
                }
                0..=11 => self.write(),
                12 | 13 => {
                    let at = self.below(self.open.len());
                    let restart = self.below(2) == 0;
                    self.truncate(at, restart);
                }
                14..=16 => {
                    let at = self.below(self.open.len());
                    self.commit(at);
                }
                17 => {
                    let at = self.below(self.open.len());
                    self.abort(at);
                }
                18 => {
                    let pages = self.db.table().heap.page_ids().unwrap();
                    let page_id = pages[self.below(pages.len())];
                    self.db.storage.bpm.flush_page(page_id).unwrap();
                }
                19 => checkpoint::fuzzy(&self.db.storage.bpm).unwrap(),
                20 => self.db.storage.bpm.checkpoint().unwrap(),
                _ => self.write(),
            }
        }
    }

    fn begin(&mut self) -> usize {
        let txn = self.db.tm.begin();
        self.open.push(Open {
            txn,
            effects: Effects::default(),
            rids: HashMap::new(),
        });
        self.open.len() - 1
    }

    /// Locks `t` for open transaction `at` as a statement would, returning
    /// whether it got the lock.
    fn lock(&self, at: usize, mode: LockMode) -> bool {
        let table = self.db.table();
        match self
            .db
            .catalog
            .lock_table(&self.open[at].txn, table.oid, mode)
        {
            Ok(()) => true,
            Err(CatalogError::LockConflict { .. } | CatalogError::ChangedSince { .. }) => false,
            Err(e) => panic!("locking t: {e}"),
        }
    }

    /// The row `id` as open transaction `at` sees it, with its rid.
    fn view(&self, at: usize, id: i64) -> Option<(Row, Rid)> {
        let open = &self.open[at];
        match open.effects.rows.get(&id) {
            Some(row) => row.map(|row| (row, open.rids[&id])),
            None if open.effects.truncated => None,
            None => self.committed.get(&id).copied(),
        }
    }

    /// The ids open transaction `at` sees.
    fn visible_ids(&self, at: usize) -> Vec<i64> {
        let open = &self.open[at];
        let committed = self.committed.keys().filter(|_| !open.effects.truncated);
        let ids: BTreeSet<i64> = committed.chain(open.effects.rows.keys()).copied().collect();
        ids.into_iter()
            .filter(|&id| self.view(at, id).is_some())
            .collect()
    }

    /// Whether another open transaction wrote row `id`.
    fn held_by_other(&self, at: usize, id: i64) -> bool {
        (0..self.open.len()).any(|o| o != at && self.open[o].effects.rows.contains_key(&id))
    }

    /// Inserts, updates or deletes a row in a random open transaction. One
    /// that conflicts is aborted.
    fn write(&mut self) {
        if self.open.is_empty() {
            self.begin();
        }
        let at = self.below(self.open.len());
        if !self.lock(at, LockMode::RowExclusive) {
            return;
        }
        let ids = self.visible_ids(at);
        let row = (self.below(1000) as i32, self.below(300));
        let wrote = match self.below(4) {
            _ if ids.len() < 4 => self.insert(at, row),
            0 | 1 => self.insert(at, row),
            pick => {
                let id = ids[self.below(ids.len())];
                if self.held_by_other(at, id) {
                    return;
                }
                let old = self.view(at, id).unwrap();
                match pick {
                    2 => self.update(at, id, old, row),
                    _ => self.delete(at, id, old),
                }
            }
        };
        match wrote {
            Ok(true) => {}
            Ok(false) | Err(storage::StorageError::Conflict { .. }) => self.abort(at),
            Err(e) => panic!("writing t: {e}"),
        }
    }

    fn insert(&mut self, at: usize, row: Row) -> storage::Result<bool> {
        let (table, indexes) = (self.db.table(), self.db.indexes());
        let indexed = self.db.indexed(&table);
        let txn = Arc::clone(&self.open[at].txn);
        let id = table.identity(0).unwrap().next_value().unwrap();
        let rid = txn.insert(&table.heap, &table.schema, &encode(id, row))?;
        self.open[at].effects.rows.insert(id, Some(row));
        self.open[at].rids.insert(id, rid);
        let (pk, by_v) = (&indexes[0], &indexes[1]);
        let pk_key = key(pk, Value::BigInt(id));
        let by_pk = RowLocator::PrimaryKey(pk_key.clone());
        Ok(
            txn.insert_entry(&indexed, &pk.index, &pk_key, &RowLocator::Rid(rid), rid)?
                && txn.insert_entry(
                    &indexed,
                    &by_v.index,
                    &key(by_v, Value::Int(row.0)),
                    &by_pk,
                    rid,
                )?,
        )
    }

    fn update(&mut self, at: usize, id: i64, old: (Row, Rid), row: Row) -> storage::Result<bool> {
        let (table, indexes) = (self.db.table(), self.db.indexes());
        let indexed = self.db.indexed(&table);
        let txn = Arc::clone(&self.open[at].txn);
        let ((old_row, old_rid), (pk, by_v)) = (old, (&indexes[0], &indexes[1]));
        let rid = txn.update(&table.heap, &table.schema, old_rid, &encode(id, row))?;
        self.open[at].effects.rows.insert(id, Some(row));
        self.open[at].rids.insert(id, rid);
        let pk_key = key(pk, Value::BigInt(id));
        if rid != old_rid {
            if !txn.insert_entry(&indexed, &pk.index, &pk_key, &RowLocator::Rid(rid), rid)? {
                return Ok(false);
            }
            txn.retire_entry(&indexed, &pk.index, &pk_key, &RowLocator::Rid(old_rid))?;
        }
        if row.0 != old_row.0 {
            let by_pk = RowLocator::PrimaryKey(pk_key);
            let new_key = key(by_v, Value::Int(row.0));
            if !txn.insert_entry(&indexed, &by_v.index, &new_key, &by_pk, rid)? {
                return Ok(false);
            }
            let old_key = key(by_v, Value::Int(old_row.0));
            txn.retire_entry(&indexed, &by_v.index, &old_key, &by_pk)?;
        }
        Ok(true)
    }

    fn delete(&mut self, at: usize, id: i64, old: (Row, Rid)) -> storage::Result<bool> {
        let (table, indexes) = (self.db.table(), self.db.indexes());
        let indexed = self.db.indexed(&table);
        let txn = Arc::clone(&self.open[at].txn);
        let ((v, _), rid) = old;
        txn.delete(&table.heap, rid)?;
        self.open[at].effects.rows.insert(id, None);
        let (pk, by_v) = (&indexes[0], &indexes[1]);
        let pk_key = key(pk, Value::BigInt(id));
        txn.retire_entry(&indexed, &pk.index, &pk_key, &RowLocator::Rid(rid))?;
        let by_pk = RowLocator::PrimaryKey(pk_key);
        txn.retire_entry(&indexed, &by_v.index, &key(by_v, Value::Int(v)), &by_pk)?;
        Ok(true)
    }

    /// Truncates `t` in open transaction `at`, if it can lock it, returning
    /// whether it did.
    fn truncate(&mut self, at: usize, restart: bool) -> bool {
        if !self.lock(at, LockMode::AccessExclusive) {
            return false;
        }
        let oid = self.db.table().oid;
        self.db
            .catalog
            .truncate(&self.open[at].txn, oid, restart)
            .unwrap();
        let open = &mut self.open[at];
        open.effects = Effects {
            truncated: true,
            rows: BTreeMap::new(),
        };
        open.rids.clear();
        true
    }

    fn commit(&mut self, at: usize) {
        let Open { txn, effects, rids } = self.open.remove(at);
        self.db.tm.commit(&txn).unwrap();
        if effects.truncated || !effects.rows.is_empty() {
            self.expect.acked.push((txn.tid(), self.fs.num_events()));
        }
        if effects.truncated {
            self.committed.clear();
        }
        for (&id, row) in &effects.rows {
            match row {
                Some(row) => self.committed.insert(id, (*row, rids[&id])),
                None => self.committed.remove(&id),
            };
        }
        self.expect.effects.insert(txn.tid(), effects);
        self.db.tm.wait_for_gc();
    }

    fn abort(&mut self, at: usize) {
        let Open { txn, effects, .. } = self.open.remove(at);
        self.db.tm.abort(&txn).unwrap();
        self.undone += usize::from(effects.truncated);
        self.db.tm.wait_for_gc();
    }

    /// Ends the workload as a crash would, leaving its open transactions
    /// running.
    fn crash(self) -> Expect {
        for open in self.open {
            std::mem::forget(open.txn);
        }
        self.expect
    }
}

/// The Tids whose `Commit` is in `fs`'s log, every segment it ever had, in
/// log order, and the highest Tid of any record.
fn commits_in(fs: &CrashFs) -> (Vec<TxnId>, TxnId) {
    let log = Log::open(Arc::new(fs.with_removed()), LOG, SEGMENT).unwrap();
    let (mut commits, mut max_tid) = (Vec::new(), INVALID_TXN_ID);
    let mut scan = log.scan(FIRST_LSN);
    while let Some(record) = scan.next_record().unwrap() {
        max_tid = max_tid.max(record.tid);
        if record.kind == Kind::Commit {
            commits.push(record.tid);
        }
    }
    (commits, max_tid)
}

/// The rows the transactions committed in `commits` leave, in order.
fn rows_after(expect: &Expect, commits: &[TxnId]) -> BTreeMap<i64, Row> {
    let mut rows = BTreeMap::new();
    for tid in commits {
        let Some(effects) = expect.effects.get(tid) else {
            continue;
        };
        if effects.truncated {
            rows.clear();
        }
        for (&id, &row) in &effects.rows {
            match row {
                Some(row) => rows.insert(id, row),
                None => rows.remove(&id),
            };
        }
    }
    rows
}

/// Recovers `image`, a crash after `events` fs events, and checks it
/// against what the workload did.
fn recover_and_check(image: &CrashFs, events: usize, expect: &Expect, at: &str) {
    let (commits, _) = commits_in(image);
    let survived: HashSet<_> = commits.iter().copied().collect();
    for &(tid, acked_at) in &expect.acked {
        assert!(
            acked_at > events || survived.contains(&tid),
            "{at}: transaction {tid}, acknowledged after event {acked_at}, is lost"
        );
    }
    let db = Db::open(image, 6);
    check(&db, &rows_after(expect, &commits), &expect.system, at);
}

/// The rows of `t` a new transaction sees, by id, with their rids.
fn visible(db: &Db) -> BTreeMap<i64, (Row, Rid)> {
    let table = db.table();
    let txn = db.tm.begin();
    let mut scan = txn.scan(&table.heap, &table.schema).unwrap();
    let mut rows = BTreeMap::new();
    while let Some(batch) = scan.next_batch().unwrap() {
        for (_, tuple) in batch {
            let values = tuple.decode(&table.schema).unwrap();
            let [Value::BigInt(id), Value::Int(v), Value::Varchar(pad)] = &values[..] else {
                panic!("bad row {values:?}");
            };
            rows.insert(*id, ((*v, pad.len()), tuple.rid().unwrap()));
        }
    }
    db.tm.commit(&txn).unwrap();
    rows
}

/// Checks that `t` holds exactly `expected` and no locked tuple; that each
/// row has its index entries and every primary key entry leads into the
/// heap, to no undone insert; that every page the db file holds is a
/// catalog page in `system` or one of `t`'s; and that the sequence hands
/// out an id above every row's.
fn check(db: &Db, expected: &BTreeMap<i64, Row>, system: &BTreeSet<PageId>, at: &str) {
    let bpm = &db.storage.bpm;
    let table = db.table();
    let heap_pages: BTreeSet<_> = table.heap.page_ids().unwrap().into_iter().collect();
    for &page_id in &heap_pages {
        let guard = bpm.read_page(page_id, AccessType::Unknown);
        for (slot, meta, _) in TablePage::new(guard.get_data()).unwrap().iter() {
            assert_eq!(
                meta.ts & TXN_UNCOMMITTED_BIT,
                0,
                "{at}: tuple ({page_id}, {slot}) is still locked by {}",
                meta.ts & !TXN_UNCOMMITTED_BIT
            );
        }
    }

    let rows = visible(db);
    let seen: BTreeMap<i64, Row> = rows.iter().map(|(&id, &(row, _))| (id, row)).collect();
    assert_eq!(&seen, expected, "{at}: rows");
    let indexes = db.indexes();
    let (pk, by_v) = (&indexes[0], &indexes[1]);
    for (&id, &((v, _), rid)) in &rows {
        let mut found = Vec::new();
        pk.index
            .scan_key(&key(pk, Value::BigInt(id)), &mut found)
            .unwrap();
        assert!(
            found.contains(&RowLocator::Rid(rid)),
            "{at}: no key entry for row {id}"
        );
        found.clear();
        by_v.index
            .scan_key(&key(by_v, Value::Int(v)), &mut found)
            .unwrap();
        let by_pk = RowLocator::PrimaryKey(key(pk, Value::BigInt(id)));
        assert!(found.contains(&by_pk), "{at}: no v entry for row {id}");
    }
    let Index::BtreeIndex(tree) = &*pk.index;
    for entry in tree.tree().begin().unwrap() {
        let (_, rid) = entry.unwrap();
        assert!(
            heap_pages.contains(&rid.page_id),
            "{at}: a key entry leads to {rid}, outside the heap"
        );
        let guard = bpm.read_page(rid.page_id, AccessType::Unknown);
        let page = TablePage::new(guard.get_data()).unwrap();
        if page.is_dead(rid.slot) {
            continue;
        }
        let (meta, _) = page.get(rid.slot).unwrap();
        assert!(
            !(meta.is_deleted && meta.ts == INVALID_TXN_ID),
            "{at}: an entry of an undone insert is left at {rid}"
        );
    }

    let reachable: BTreeSet<_> = db.reachable().union(system).copied().collect();
    let allocated = db.allocated();
    let leaked: Vec<_> = allocated.difference(&reachable).collect();
    let lost: Vec<_> = reachable.difference(&allocated).collect();
    assert!(
        leaked.is_empty() && lost.is_empty(),
        "{at}: pages nothing reaches {leaked:?}, pages reached but freed {lost:?}"
    );

    let next = table.identity(0).unwrap().next_value().unwrap();
    if let Some((&max, _)) = rows.last_key_value() {
        assert!(
            next > max,
            "{at}: the sequence hands out {next}, but row {max} is there"
        );
    }
}

/// A truncate, with RESTART IDENTITY or without, of a table with rows and
/// indexes, in transaction `at`, followed by inserts that grow the new
/// heap and trees past one page.
fn truncate_and_fill(workload: &mut Workload, at: usize, restart: bool) {
    assert!(
        workload.truncate(at, restart),
        "the truncate could not lock t"
    );
    for v in 0..40 {
        assert!(matches!(workload.insert(at, (v, 250)), Ok(true)));
    }
}

/// Leaves `t` with rows whose ids a restarted sequence would hand out
/// again, all committed.
fn fill(workload: &mut Workload) {
    let at = workload.begin();
    assert!(workload.lock(at, LockMode::RowExclusive));
    for v in 0..60 {
        assert!(matches!(workload.insert(at, (v, 200)), Ok(true)));
    }
    workload.commit(at);
}

#[test]
fn every_crash_point_keeps_exactly_the_committed_truncates() {
    let fs = CrashFs::new();
    let mut workload = Workload::new(&fs, 8, 0x7c0f);
    workload.run(240);
    // A truncate left running at the crash, after one that committed.
    while !workload.open.is_empty() {
        workload.commit(0);
    }
    fill(&mut workload);
    let at = workload.begin();
    truncate_and_fill(&mut workload, at, true);
    workload.commit(at);
    fill(&mut workload);
    let at = workload.begin();
    truncate_and_fill(&mut workload, at, true);
    let (start, undone) = (workload.setup, workload.undone);
    let expect = workload.crash();

    let truncates = expect.effects.values().filter(|e| e.truncated).count();
    assert!(
        truncates >= 4 && undone >= 2,
        "only {truncates} committed truncates and {undone} rolled back"
    );
    let mut crashes = 0;
    fs.for_each_moment(|n, moment| {
        if n < start {
            return;
        }
        for lost in [Lost::Nothing, Lost::Everything, Lost::Some(n as u64)] {
            let at = format!("crash after event {n}, losing {lost:?}");
            recover_and_check(&moment.crash(lost), n, &expect, &at);
            crashes += 1;
        }
    });
    assert!(crashes > 900, "only {crashes} crash points");
}

/// A committed truncate frees the old storage only once no reader needs it,
/// and logs `End` after that. A crash anywhere from its `Commit` on, its
/// stamps, the free and the `End` included, keeps the truncate and frees
/// the old storage.
#[test]
fn a_crash_between_a_truncates_commit_and_its_end_frees_the_old_storage() {
    for restart in [false, true] {
        let fs = CrashFs::new();
        let mut workload = Workload::new(&fs, 8, 0x51de);
        fill(&mut workload);
        // Holds back garbage collection, and with it the free.
        let reader = workload.begin();
        let at = workload.begin();
        let old = workload.db.table().first_page_id();
        truncate_and_fill(&mut workload, at, restart);
        let tid = workload.open[at].txn.tid();
        workload.db.storage.bpm.log().flush_all().unwrap();
        let before = fs.num_events();
        workload.commit(at);
        let committed = fs.num_events();
        let disk = Arc::clone(workload.db.storage.bpm.disk_manager());
        assert!(disk.has_page(old), "the old heap went while a reader ran");
        workload.abort(reader);
        assert!(!disk.has_page(old), "the old heap is still there");
        // `End` is not synced, and a crash test sees only what was written.
        workload.db.storage.bpm.log().flush_all().unwrap();
        let after = fs.num_events();
        let expect = workload.crash();

        let image = fs.crash_after(after, Lost::Nothing);
        let log = Log::open(Arc::new(image.with_removed()), LOG, SEGMENT).unwrap();
        let mut scan = log.scan(FIRST_LSN);
        let mut kinds = Vec::new();
        while let Some(record) = scan.next_record().unwrap() {
            if record.tid == tid && !matches!(record.kind, Kind::Update) {
                kinds.push(record.kind);
            }
        }
        assert_eq!(kinds.first(), Some(&Kind::Commit), "{kinds:?}");
        assert_eq!(kinds.last(), Some(&Kind::End), "{kinds:?}");

        for n in before..=after {
            for lost in [Lost::Nothing, Lost::Everything, Lost::Some(n as u64)] {
                let at = format!(
                    "restart {restart}: crash after event {n} of a commit {before}..{committed}, freed by {after}, losing {lost:?}"
                );
                recover_and_check(&fs.crash_after(n, lost), n, &expect, &at);
            }
        }
    }
}

/// A rollback of a truncate puts the catalog rows and the sequence back,
/// then frees the new storage, compensating each step, so a crash in the
/// middle of it finishes it.
#[test]
fn a_crash_during_a_truncates_rollback_finishes_it() {
    for restart in [false, true] {
        let fs = CrashFs::new();
        let mut workload = Workload::new(&fs, 6, 0xab07);
        fill(&mut workload);
        let reader = workload.begin();
        let at = workload.begin();
        truncate_and_fill(&mut workload, at, restart);
        workload.db.storage.bpm.log().flush_all().unwrap();
        let before = fs.num_events();
        workload.abort(at);
        let after = fs.num_events();
        // Its inserts went with the storage undo freed.
        assert_eq!(workload.db.tm.garbage_len(), 0, "garbage in freed storage");
        workload.abort(reader);
        let expect = workload.crash();

        assert!(
            after - before > 4,
            "the rollback wrote only {} events",
            after - before
        );
        for n in before..=after {
            for lost in [Lost::Nothing, Lost::Everything, Lost::Some(n as u64)] {
                let at = format!(
                    "restart {restart}: crash after event {n} of a rollback {before}..{after}, losing {lost:?}"
                );
                recover_and_check(&fs.crash_after(n, lost), n, &expect, &at);
            }
        }
    }
}

/// Recovery's own records, the frees and compensations that finish a
/// truncate, bring a second crash, anywhere in the first recovery, back to
/// the same table.
#[test]
fn a_crash_during_recovery_finishes_the_truncates_the_same_way() {
    let fs = CrashFs::new();
    let mut workload = Workload::new(&fs, 6, 0x0dd5);
    fill(&mut workload);
    // One committed truncate whose free waits for the reader, and one left
    // running.
    let reader = workload.begin();
    let at = workload.begin();
    truncate_and_fill(&mut workload, at, true);
    workload.commit(at);
    let at = workload.begin();
    assert!(workload.lock(at, LockMode::RowExclusive));
    for v in 0..20 {
        assert!(matches!(workload.insert(at, (v, 250)), Ok(true)));
    }
    workload.commit(at);
    let at = workload.begin();
    truncate_and_fill(&mut workload, at, true);
    let _ = reader;
    workload.db.storage.bpm.log().flush_all().unwrap();
    let expect = workload.crash();

    let image = fs.crash_after(fs.num_events(), Lost::Everything);
    let (commits, _) = commits_in(&image);
    let rows = rows_after(&expect, &commits);
    drop(Db::open(&image, 6));
    let recovering = image.num_events();
    assert!(recovering > 5, "recovery wrote only {recovering} events");
    image.for_each_moment(|n, moment| {
        for again in [Lost::Nothing, Lost::Everything, Lost::Some(n as u64)] {
            let crashed = moment.crash(again);
            let db = Db::open(&crashed, 6);
            let at = format!("crash after event {n} of {recovering} in recovery, losing {again:?}");
            check(&db, &rows, &expect.system, &at);
        }
    });
}

/// A transaction that writes the table, truncates it, writes the new
/// storage and truncates that too: its commit frees two storages, one of
/// them with tuples its own commit stamped, and its rollback frees the two
/// new ones in turn.
#[test]
fn a_table_truncated_twice_in_one_transaction() {
    for commit in [true, false] {
        let fs = CrashFs::new();
        let mut workload = Workload::new(&fs, 6, 0x2b2b);
        fill(&mut workload);
        let reader = workload.begin();
        let at = workload.begin();
        assert!(workload.lock(at, LockMode::RowExclusive));
        for v in 0..10 {
            assert!(matches!(workload.insert(at, (v, 250)), Ok(true)));
        }
        truncate_and_fill(&mut workload, at, false);
        truncate_and_fill(&mut workload, at, true);
        workload.db.storage.bpm.log().flush_all().unwrap();
        let before = fs.num_events();
        match commit {
            true => workload.commit(at),
            false => workload.abort(at),
        }
        workload.abort(reader);
        workload.db.storage.bpm.log().flush_all().unwrap();
        let after = fs.num_events();
        let expect = workload.crash();

        for n in before..=after {
            for lost in [Lost::Nothing, Lost::Everything, Lost::Some(n as u64)] {
                let at = format!(
                    "commit {commit}: crash after event {n} of {before}..{after}, losing {lost:?}"
                );
                recover_and_check(&fs.crash_after(n, lost), n, &expect, &at);
            }
        }
    }
}

/// Without page writes the log is all there is, so cutting it after any
/// record leaves the truncates whose `Commit` is below the cut, and each
/// state a truncate passes through: its storage made, its catalog rows
/// changed, its old storage freed with no `End` yet, its undo part done.
#[test]
fn every_prefix_of_the_log_keeps_the_truncates_below_the_cut() {
    let fs = CrashFs::new();
    let mut workload = Workload::with_segment(&fs, 512, u64::MAX, 0x9f1c);
    let durable = workload.db.storage.bpm.log().end();
    fill(&mut workload);
    let reader = workload.begin();
    let at = workload.begin();
    assert!(workload.lock(at, LockMode::RowExclusive));
    for v in 0..10 {
        assert!(matches!(workload.insert(at, (v, 250)), Ok(true)));
    }
    truncate_and_fill(&mut workload, at, false);
    truncate_and_fill(&mut workload, at, true);
    workload.commit(at);
    workload.abort(reader);
    for end in ["rollback", "open"] {
        let at = workload.begin();
        truncate_and_fill(&mut workload, at, true);
        if end == "rollback" {
            workload.abort(at);
        }
    }
    workload.db.storage.bpm.log().flush_all().unwrap();
    let expect = workload.crash();

    let segment = std::path::PathBuf::from(format!("{LOG}.{:08}", 1));
    let bytes = fs.contents(&segment);
    let log = Log::open(Arc::new(fs.crash_now()), LOG, u64::MAX).unwrap();
    let mut cuts = vec![log.end()];
    let mut scan = log.scan(durable);
    while let Some(record) = scan.next_record().unwrap() {
        cuts.push(record.lsn);
    }
    assert!(cuts.len() > 100, "{} records", cuts.len());
    for cut in cuts {
        let image = fs.with_contents(&segment, &bytes[..cut as usize]);
        let (commits, _) = commits_in(&image);
        let db = Db::open(&image, 64);
        let at = format!("log cut at {cut}");
        check(&db, &rows_after(&expect, &commits), &expect.system, &at);
    }
}
