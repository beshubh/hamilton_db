//! The system tables that store the catalog, and their row formats.
//!
//! ```text
//! tables         (oid INT, name VARCHAR, first_page_id INT, kind INT)
//! columns        (table_oid INT, position INT, name VARCHAR, type_id INT,
//!                 max_len INT, nullable BOOL, sequence INT NULL)
//! indexes        (oid INT, name VARCHAR, table_oid INT, header_page_id INT,
//!                 kind INT)
//! index_columns  (index_oid INT, position INT, column INT)
//! ```
//!
//! Each is an ordinary table heap whose first page is recorded on page 0.
//! A DDL statement writes its rows as its transaction's changes, so one
//! that does not commit leaves none: undo leaves them deleted, and scans
//! skip deleted rows.

use std::sync::{Arc, LazyLock};

use common::{Column, DataType, IndexKind, PageId, Rid, Schema, Tuple, Value};
use storage::buffer::buffer_pool_manager::BufferPoolManager;
use storage::table::table_heap::TableHeap;
use storage::table::table_page::TupleMeta;
use storage::wal::Logged;

use crate::catalog::{IndexOid, MAX_NAME_LEN, RelationKind, TableOid};
use crate::error::{CatalogError, Result};
use crate::header_page::SystemTableRoots;

/// Catalog rows are read without a snapshot, so they carry `ts` 0, as if
/// committed at the start of time, even when a transaction writes them: its
/// commit has nothing to stamp, and its undo leaves them deleted.
pub(crate) const CATALOG_TS: u64 = 0;

fn name_column(name: &str) -> Column {
    Column::new(name, DataType::Varchar(MAX_NAME_LEN), false)
}

fn int_column(name: &str) -> Column {
    Column::new(name, DataType::Int, false)
}

static TABLES_SCHEMA: LazyLock<Schema> = LazyLock::new(|| {
    Schema::new(vec![
        int_column("oid"),
        name_column("name"),
        int_column("first_page_id"),
        int_column("kind"),
    ])
});

static COLUMNS_SCHEMA: LazyLock<Schema> = LazyLock::new(|| {
    Schema::new(vec![
        int_column("table_oid"),
        int_column("position"),
        name_column("name"),
        int_column("type_id"),
        int_column("max_len"),
        Column::new("nullable", DataType::Bool, false),
        Column::new("sequence", DataType::Int, true),
    ])
});

static INDEXES_SCHEMA: LazyLock<Schema> = LazyLock::new(|| {
    Schema::new(vec![
        int_column("oid"),
        name_column("name"),
        int_column("table_oid"),
        int_column("header_page_id"),
        int_column("kind"),
    ])
});

static INDEX_COLUMNS_SCHEMA: LazyLock<Schema> = LazyLock::new(|| {
    Schema::new(vec![
        int_column("index_oid"),
        int_column("position"),
        int_column("column"),
    ])
});

/// A row of `tables`.
pub(crate) struct TableRow {
    pub oid: TableOid,
    pub name: String,
    pub first_page_id: PageId,
    pub kind: RelationKind,
}

/// A row of `columns`: column `position` of table `table_oid`.
pub(crate) struct ColumnRow {
    pub table_oid: TableOid,
    pub position: usize,
    pub column: Column,
    /// For a `GENERATED BY DEFAULT AS IDENTITY` column, the sequence it
    /// takes its values from.
    pub sequence: Option<TableOid>,
}

/// A row of `indexes`.
pub(crate) struct IndexRow {
    pub oid: IndexOid,
    pub name: String,
    pub table_oid: TableOid,
    pub header_page_id: PageId,
    pub kind: IndexKind,
    pub constraint: bool,
}

/// A row of `index_columns`: key column `position` of index `index_oid` is
/// column `column` of its table.
pub(crate) struct IndexColumnRow {
    pub index_oid: IndexOid,
    pub position: usize,
    pub column: usize,
}

/// The heaps of the four system tables.
pub(crate) struct SystemTables {
    tables: TableHeap,
    columns: TableHeap,
    indexes: TableHeap,
    index_columns: TableHeap,
}

impl SystemTables {
    /// Creates the system tables, empty.
    pub fn create(bpm: &Arc<BufferPoolManager>) -> Result<Self> {
        Ok(Self {
            tables: TableHeap::create(Arc::clone(bpm))?,
            columns: TableHeap::create(Arc::clone(bpm))?,
            indexes: TableHeap::create(Arc::clone(bpm))?,
            index_columns: TableHeap::create(Arc::clone(bpm))?,
        })
    }

    pub fn open(bpm: &Arc<BufferPoolManager>, roots: SystemTableRoots) -> Result<Self> {
        Ok(Self {
            tables: TableHeap::open(Arc::clone(bpm), roots.tables)?,
            columns: TableHeap::open(Arc::clone(bpm), roots.columns)?,
            indexes: TableHeap::open(Arc::clone(bpm), roots.indexes)?,
            index_columns: TableHeap::open(Arc::clone(bpm), roots.index_columns)?,
        })
    }

    pub fn heaps(&self) -> [&TableHeap; 4] {
        [
            &self.tables,
            &self.columns,
            &self.indexes,
            &self.index_columns,
        ]
    }

    pub fn roots(&self) -> SystemTableRoots {
        SystemTableRoots {
            tables: self.tables.first_page_id(),
            columns: self.columns.first_page_id(),
            indexes: self.indexes.first_page_id(),
            index_columns: self.index_columns.first_page_id(),
        }
    }

    pub fn insert_table(&self, by: Logged<'_>, row: &TableRow) -> Result<()> {
        let values = [
            oid_value(row.oid),
            Value::Varchar(row.name.clone()),
            Value::Int(row.first_page_id),
            Value::Int(encode_relation_kind(row.kind)),
        ];
        insert(by, &self.tables, &TABLES_SCHEMA, &values)
    }

    pub fn insert_column(&self, by: Logged<'_>, row: &ColumnRow) -> Result<()> {
        let (type_id, max_len) = encode_type(row.column.data_type);
        let values = [
            oid_value(row.table_oid),
            int_value(row.position),
            Value::Varchar(row.column.name.clone()),
            Value::Int(type_id),
            Value::Int(max_len),
            Value::Bool(row.column.nullable),
            row.sequence.map_or(Value::Null, oid_value),
        ];
        insert(by, &self.columns, &COLUMNS_SCHEMA, &values)
    }

    pub fn insert_index(&self, by: Logged<'_>, row: &IndexRow) -> Result<()> {
        let values = [
            oid_value(row.oid),
            Value::Varchar(row.name.clone()),
            oid_value(row.table_oid),
            Value::Int(row.header_page_id),
            Value::Int(encode_kind(row.kind, row.constraint)),
        ];
        insert(by, &self.indexes, &INDEXES_SCHEMA, &values)
    }

    pub fn insert_index_column(&self, by: Logged<'_>, row: &IndexColumnRow) -> Result<()> {
        let values = [
            oid_value(row.index_oid),
            int_value(row.position),
            int_value(row.column),
        ];
        insert(by, &self.index_columns, &INDEX_COLUMNS_SCHEMA, &values)
    }

    /// Points the `tables` row of `oid` at a new first page, as `by`'s
    /// change.
    pub fn set_first_page_id(&self, by: Logged<'_>, oid: TableOid, page_id: PageId) -> Result<()> {
        set_page_id(by, &self.tables, &TABLES_SCHEMA, oid, 2, page_id)
    }

    /// Points the `indexes` row of `oid` at a new header page, as `by`'s
    /// change.
    pub fn set_header_page_id(&self, by: Logged<'_>, oid: IndexOid, page_id: PageId) -> Result<()> {
        set_page_id(by, &self.indexes, &INDEXES_SCHEMA, oid, 3, page_id)
    }

    /// Deletes the `tables` row of `oid`, as `by`'s change. Returns whether
    /// there was one.
    pub fn delete_table(&self, by: Logged<'_>, oid: TableOid) -> Result<bool> {
        Ok(delete_rows(by, &self.tables, &TABLES_SCHEMA, oid)? > 0)
    }

    /// Deletes the `columns` rows of table `table_oid`, as `by`'s change.
    pub fn delete_columns(&self, by: Logged<'_>, table_oid: TableOid) -> Result<()> {
        delete_rows(by, &self.columns, &COLUMNS_SCHEMA, table_oid).map(drop)
    }

    /// Deletes the `indexes` row of `oid`, as `by`'s change.
    pub fn delete_index(&self, by: Logged<'_>, oid: IndexOid) -> Result<()> {
        delete_rows(by, &self.indexes, &INDEXES_SCHEMA, oid).map(drop)
    }

    /// Deletes the `index_columns` rows of index `index_oid`, as `by`'s
    /// change.
    pub fn delete_index_columns(&self, by: Logged<'_>, index_oid: IndexOid) -> Result<()> {
        delete_rows(by, &self.index_columns, &INDEX_COLUMNS_SCHEMA, index_oid).map(drop)
    }

    pub fn scan_tables(&self) -> Result<Vec<TableRow>> {
        scan(&self.tables, &TABLES_SCHEMA, |values| {
            Ok(TableRow {
                oid: as_oid(&values[0])?,
                name: as_string(&values[1])?,
                first_page_id: as_int(&values[2])?,
                kind: decode_relation_kind(as_int(&values[3])?)?,
            })
        })
    }

    pub fn scan_columns(&self) -> Result<Vec<ColumnRow>> {
        scan(&self.columns, &COLUMNS_SCHEMA, |values| {
            let data_type = decode_type(as_int(&values[3])?, as_int(&values[4])?)?;
            Ok(ColumnRow {
                table_oid: as_oid(&values[0])?,
                position: as_index(&values[1])?,
                column: Column::new(as_string(&values[2])?, data_type, as_bool(&values[5])?),
                sequence: match &values[6] {
                    Value::Null => None,
                    value => Some(as_oid(value)?),
                },
            })
        })
    }

    pub fn scan_indexes(&self) -> Result<Vec<IndexRow>> {
        scan(&self.indexes, &INDEXES_SCHEMA, |values| {
            let (kind, constraint) = decode_kind(as_int(&values[4])?)?;
            Ok(IndexRow {
                oid: as_oid(&values[0])?,
                name: as_string(&values[1])?,
                table_oid: as_oid(&values[2])?,
                header_page_id: as_int(&values[3])?,
                kind,
                constraint,
            })
        })
    }

    pub fn scan_index_columns(&self) -> Result<Vec<IndexColumnRow>> {
        scan(&self.index_columns, &INDEX_COLUMNS_SCHEMA, |values| {
            Ok(IndexColumnRow {
                index_oid: as_oid(&values[0])?,
                position: as_index(&values[1])?,
                column: as_index(&values[2])?,
            })
        })
    }
}

/// Sets column `column`, a page id, of the row whose first column is `oid`,
/// as `by`'s change. The row keeps its size, so it is changed in place.
fn set_page_id(
    by: Logged<'_>,
    heap: &TableHeap,
    schema: &Schema,
    oid: u32,
    column: usize,
    page_id: PageId,
) -> Result<()> {
    let (rid, meta, mut values) = find_row(heap, schema, oid)?;
    values[column] = Value::Int(page_id);
    heap.update_in_place(by, rid, &meta, &Tuple::encode(schema, &values)?)?;
    Ok(())
}

/// The row whose first column is `oid`.
fn find_row(heap: &TableHeap, schema: &Schema, oid: u32) -> Result<(Rid, TupleMeta, Vec<Value>)> {
    for row in heap.iter()? {
        let (meta, tuple) = row?;
        let values = tuple.decode(schema)?;
        if as_oid(&values[0])? == oid {
            let rid = tuple.rid().expect("the heap's rows carry their rid");
            return Ok((rid, meta, values));
        }
    }
    Err(CatalogError::Corrupt(format!(
        "no catalog row for oid {oid}"
    )))
}

/// Marks deleted every row whose first column is `oid`, as `by`'s change,
/// and returns how many. Each keeps its payload, so undo puts it back whole.
fn delete_rows(by: Logged<'_>, heap: &TableHeap, schema: &Schema, oid: u32) -> Result<usize> {
    let mut matching = Vec::new();
    for row in heap.iter()? {
        let (meta, tuple) = row?;
        if as_oid(&tuple.decode(schema)?[0])? == oid {
            matching.push((meta, tuple));
        }
    }
    let deleted = matching.len();
    for (meta, tuple) in matching {
        let rid = tuple.rid().expect("the heap's rows carry their rid");
        let meta = TupleMeta {
            is_deleted: true,
            ..meta
        };
        heap.update_in_place(by, rid, &meta, &tuple)?;
    }
    Ok(deleted)
}

fn insert(by: Logged<'_>, heap: &TableHeap, schema: &Schema, values: &[Value]) -> Result<()> {
    let tuple = Tuple::encode(schema, values)?;
    heap.insert(by, &TupleMeta::new(CATALOG_TS), &tuple)?;
    Ok(())
}

fn scan<R>(
    heap: &TableHeap,
    schema: &Schema,
    decode: impl Fn(&[Value]) -> Result<R>,
) -> Result<Vec<R>> {
    let mut rows = Vec::new();
    for row in heap.iter()? {
        let (_, tuple) = row?;
        rows.push(decode(&tuple.decode(schema)?)?);
    }
    Ok(rows)
}

fn encode_type(data_type: DataType) -> (i32, i32) {
    match data_type {
        DataType::Int => (0, 0),
        DataType::BigInt => (1, 0),
        DataType::Bool => (2, 0),
        DataType::Varchar(max_len) => (3, max_len as i32),
        DataType::Array => (4, 0),
        DataType::Double => (5, 0),
        DataType::Timestamptz => (6, 0),
    }
}

fn decode_type(type_id: i32, max_len: i32) -> Result<DataType> {
    Ok(match type_id {
        0 => DataType::Int,
        1 => DataType::BigInt,
        2 => DataType::Bool,
        3 => DataType::Varchar(max_len as u32),
        4 => DataType::Array,
        5 => DataType::Double,
        6 => DataType::Timestamptz,
        other => return Err(CatalogError::Corrupt(format!("unknown type id {other}"))),
    })
}

fn encode_relation_kind(kind: RelationKind) -> i32 {
    match kind {
        RelationKind::Table => 0,
        RelationKind::Sequence => 1,
    }
}

fn decode_relation_kind(kind: i32) -> Result<RelationKind> {
    Ok(match kind {
        0 => RelationKind::Table,
        1 => RelationKind::Sequence,
        other => {
            return Err(CatalogError::Corrupt(format!(
                "unknown relation kind {other}"
            )));
        }
    })
}

const UNIQUE: IndexKind = IndexKind::Unique {
    nulls_distinct: true,
};
const UNIQUE_NULLS_NOT_DISTINCT: IndexKind = IndexKind::Unique {
    nulls_distinct: false,
};

const INDEX_KINDS: [(i32, IndexKind, bool); 6] = [
    (0, IndexKind::Plain, false),
    (1, UNIQUE, false),
    (2, UNIQUE_NULLS_NOT_DISTINCT, false),
    (3, IndexKind::PrimaryKey, true),
    (4, UNIQUE, true),
    (5, UNIQUE_NULLS_NOT_DISTINCT, true),
];

fn encode_kind(kind: IndexKind, constraint: bool) -> i32 {
    let (code, ..) = INDEX_KINDS
        .iter()
        .find(|&&(_, k, c)| k == kind && c == constraint)
        .expect("a primary key is a constraint, a plain index is not");
    *code
}

fn decode_kind(code: i32) -> Result<(IndexKind, bool)> {
    INDEX_KINDS
        .iter()
        .find(|&&(c, ..)| c == code)
        .map(|&(_, kind, constraint)| (kind, constraint))
        .ok_or_else(|| CatalogError::Corrupt(format!("unknown index kind {code}")))
}

fn oid_value(oid: u32) -> Value {
    Value::Int(oid as i32)
}

fn int_value(n: usize) -> Value {
    Value::Int(n as i32)
}

fn as_int(value: &Value) -> Result<i32> {
    match *value {
        Value::Int(n) => Ok(n),
        _ => Err(corrupt_value(value)),
    }
}

fn as_oid(value: &Value) -> Result<u32> {
    as_int(value).map(|n| n as u32)
}

fn as_index(value: &Value) -> Result<usize> {
    usize::try_from(as_int(value)?).map_err(|_| corrupt_value(value))
}

fn as_bool(value: &Value) -> Result<bool> {
    match *value {
        Value::Bool(b) => Ok(b),
        _ => Err(corrupt_value(value)),
    }
}

fn as_string(value: &Value) -> Result<String> {
    match value {
        Value::Varchar(s) => Ok(s.clone()),
        _ => Err(corrupt_value(value)),
    }
}

fn corrupt_value(value: &Value) -> CatalogError {
    CatalogError::Corrupt(format!("unexpected value {value} in a system table"))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn types_round_trip() {
        for data_type in [
            DataType::Int,
            DataType::BigInt,
            DataType::Double,
            DataType::Bool,
            DataType::Varchar(255),
            DataType::Timestamptz,
        ] {
            let (type_id, max_len) = encode_type(data_type);
            assert_eq!(decode_type(type_id, max_len).unwrap(), data_type);
        }
        assert!(matches!(decode_type(9, 0), Err(CatalogError::Corrupt(_))));
    }

    #[test]
    fn relation_kinds_round_trip() {
        for kind in [RelationKind::Table, RelationKind::Sequence] {
            assert_eq!(
                decode_relation_kind(encode_relation_kind(kind)).unwrap(),
                kind
            );
        }
        assert!(matches!(
            decode_relation_kind(2),
            Err(CatalogError::Corrupt(_))
        ));
    }

    #[test]
    fn index_kinds_round_trip() {
        for (kind, constraint) in [
            (IndexKind::Plain, false),
            (UNIQUE, false),
            (UNIQUE_NULLS_NOT_DISTINCT, false),
            (UNIQUE, true),
            (UNIQUE_NULLS_NOT_DISTINCT, true),
            (IndexKind::PrimaryKey, true),
        ] {
            let code = encode_kind(kind, constraint);
            assert_eq!(decode_kind(code).unwrap(), (kind, constraint));
        }
        assert!(matches!(decode_kind(6), Err(CatalogError::Corrupt(_))));
    }
}
